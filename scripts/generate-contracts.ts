import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import { createApp, createDocument } from '../apps/api/src/app';

async function main() {
  const app = await createApp();
  try {
    const document = createDocument(app);
    const schema = `${JSON.stringify(document, null, 2)}\n`;
    const types = astToString(
      await openapiTS(document as Parameters<typeof openapiTS>[0]),
    );
    const routes: Record<string, object> = {};
    for (const [path, methods] of Object.entries(document.paths)) {
      for (const [method, operation] of Object.entries(methods ?? {})) {
        if (
          !operation ||
          typeof operation !== 'object' ||
          !('operationId' in operation) ||
          typeof operation.operationId !== 'string'
        )
          continue;
        const successStatus = Number(
          Object.keys(operation.responses).find((status) =>
            /^2\d\d$/.test(status),
          ),
        );
        routes[operation.operationId] = {
          path,
          method: method.toUpperCase(),
          successStatus,
        };
      }
    }
    const client = `// Generated by scripts/generate-contracts.ts. Do not edit.\nimport type { operations } from './schema';\nexport const routes = ${JSON.stringify(routes, null, 2)} as const;\nexport type OperationName = keyof typeof routes;\ntype ResponseOf<T> = T extends {content: {'application/json': infer R}} ? R : never;\nexport type ApiResult<N extends OperationName> = operations[N] extends {responses: infer R} ? ResponseOf<R[Extract<keyof R, 200 | 201 | 202>]> : never;\nexport type ApiBody<N extends OperationName> = operations[N] extends {requestBody: {content: {'application/json': infer B}}} ? B : never;\nexport type Transport = (request: {path: string; method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE'; body?: unknown; credential?: string; admin?: boolean}) => Promise<{status: number; data: unknown}>;\nexport function createApiClient(transport: Transport) {\n  return async function call<N extends OperationName>(name: N, options: {body?: ApiBody<N>; credential?: string; admin?: boolean} = {}): Promise<ApiResult<N>> {\n    const route = routes[name];\n    const response = await transport({...route, ...options});\n    if (response.status !== route.successStatus) throw new ApiError(response.status, response.data);\n    return response.data as ApiResult<N>;\n  };\n}\nexport class ApiError extends Error {\n  constructor(public readonly status: number, public readonly data: unknown) {\n    super(typeof data === 'object' && data !== null && 'message' in data && typeof data.message === 'string' ? data.message : '请求失败，请稍后重试');\n  }\n}\n`;
    const target = resolve('packages/contracts');
    mkdirSync(target, { recursive: true });
    for (const [name, content] of [
      ['openapi.json', schema],
      ['schema.d.ts', types],
      ['client.ts', client],
    ] as const) {
      const path = resolve(target, name);
      if (process.argv.includes('--check')) {
        if (readFileSync(path, 'utf8').replace(/\r\n/g, '\n') !== content)
          throw new Error(`Contract drift: ${name}`);
      } else writeFileSync(path, content);
    }
    console.log(
      process.argv.includes('--check')
        ? 'OpenAPI and generated types match.'
        : 'OpenAPI and types generated.',
    );
  } finally {
    await app.close();
  }
}
main().catch(() => {
  console.error(
    'Contract generation failed; verify MySQL and contract output.',
  );
  process.exitCode = 1;
});
